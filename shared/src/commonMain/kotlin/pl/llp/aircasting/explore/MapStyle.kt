/**
 * Legacy's Google Maps style for the current theme (legacy `setMapTypeToNormalWithStyle`).
 * Dark = the theme's background is dark, so it follows the in-app dark-mode setting, not just the OS.
 */
@Composable
internal fun mapStyle(): String =
  if (MaterialTheme.colorScheme.background.luminance() < 0.5f) MAP_STYLE_DARK else MAP_STYLE_LIGHT
